// Build the badecision package into dist/.
//   node scripts/build.ts                       # uses the committed kernel/bdm_kernel.wasm
//   node scripts/build.ts --kernel              # recompile the kernel first (needs clang with wasm32 + wasm-ld)
//   node scripts/build.ts --model ../../models/exp-distilled/model.bin
//   node scripts/build.ts --head ../../models/serious/head.json     # the serious model's head (default shown)
//
// 1. copy the shared model/horoscope code from the repo's src/ into src/core/
// 2. inline the model and the kernel as base64 into src/generated/
// 3. tsc
// 4. check dist/ is bundler-safe (no node: imports, no import.meta.url) and the kernel stays sync-compilable

import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(PKG, '../..');
const args = process.argv.slice(2);
const flag = (name: string) => { const i = args.indexOf(name); return i < 0 ? undefined : (args[i + 1] ?? ''); };

const CORE = ['features.js', 'model.js', 'horoscope.js', 'omens.js', 'decider.js', 'gguf.js', 'bpe.js', 'smol.js'];
const KERNEL = join(PKG, 'kernel/bdm_kernel.wasm');
const SMOL_KERNEL = join(PKG, 'kernel/smol_kernel.wasm');
const HEAD = resolve(flag('--head') ?? join(ROOT, 'models/serious/head.json'));
const MODEL = resolve(flag('--model') ?? join(ROOT, 'models/tiny/model.bin'));
const SYNC_COMPILE_LIMIT = 4096; // Chrome refuses synchronous WebAssembly.Module() above 4 KB on the main thread

if (args.includes('--kernel')) {
  execFileSync('clang', [
    '--target=wasm32', '-O3', '-msimd128', '-nostdlib', '-ffreestanding', '-Wall',
    '-Wl,--no-entry', '-Wl,--strip-all', '-o', KERNEL, join(PKG, 'kernel/bdm_kernel.c'),
  ], { stdio: 'inherit' });
  execFileSync('clang', [
    '--target=wasm32', '-O3', '-msimd128', '-nostdlib', '-ffreestanding', '-Wall',
    '-Wl,--no-entry', '-Wl,--strip-all', '-o', SMOL_KERNEL, join(PKG, 'kernel/smol_kernel.c'),
  ], { stdio: 'inherit' });
}

const kernel = readFileSync(KERNEL);
if (kernel.length > SYNC_COMPILE_LIMIT) throw new Error(`kernel is ${kernel.length} B, over the ${SYNC_COMPILE_LIMIT} B sync-compile limit`);
const model = readFileSync(MODEL);

rmSync(join(PKG, 'src/core'), { recursive: true, force: true });
mkdirSync(join(PKG, 'src/core'), { recursive: true });
for (const f of CORE) cpSync(join(ROOT, 'src', f), join(PKG, 'src/core', f));

mkdirSync(join(PKG, 'src/generated'), { recursive: true });
const banner = (what: string, from: string) => `// Generated by scripts/build.ts from ${from}. Do not edit.\n// ${what}\n`;
writeFileSync(join(PKG, 'src/generated/model-data.ts'),
  `${banner(`model weights, ${model.length} bytes`, relative(PKG, MODEL))}export const MODEL_BASE64: string = '${model.toString('base64')}';\n`);
const smolKernel = readFileSync(SMOL_KERNEL); // compiled asynchronously, so no size limit
writeFileSync(join(PKG, 'src/generated/smol-kernel-data.ts'),
  `${banner(`serious-model WebAssembly kernel, ${smolKernel.length} bytes`, 'kernel/smol_kernel.wasm')}export const SMOL_KERNEL_BASE64: string = '${smolKernel.toString('base64')}';\n`);
const head = JSON.parse(readFileSync(HEAD, 'utf8'));
if (head.format !== 'badecision-head/1') throw new Error(`${HEAD} is not a badecision head`);
writeFileSync(join(PKG, 'src/generated/head-data.ts'), `${banner(`serious-model head, ${head.hidden} hidden units, test accuracy ${head.test.accuracy}`, relative(PKG, HEAD))}export const HEAD = ${JSON.stringify({
  hidden: head.hidden, temperature: head.temperature, test: head.test, mu: head.mu, sd: head.sd, W1: head.W1, b1: head.b1, W2: head.W2, b2: head.b2,
})} as const;\n`);
writeFileSync(join(PKG, 'src/generated/kernel-data.ts'),
  `${banner(`WebAssembly kernel, ${kernel.length} bytes`, 'kernel/bdm_kernel.wasm')}export const KERNEL_BASE64: string = '${kernel.toString('base64')}';\n`);

rmSync(join(PKG, 'dist'), { recursive: true, force: true });
execFileSync(join(PKG, 'node_modules/.bin/tsc'), ['-p', join(PKG, 'tsconfig.json')], { stdio: 'inherit' });

const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(join(PKG, 'dist'));
for (const f of files.filter((x) => x.endsWith('.js'))) {
  const src = readFileSync(f, 'utf8');
  if (/\bfrom\s*['"]node:|\bimport\(\s*['"]node:|\brequire\(/.test(src)) throw new Error(`${relative(PKG, f)} imports Node built-ins`);
  if (src.includes('import.meta.url')) throw new Error(`${relative(PKG, f)} uses import.meta.url`);
}

const kb = (n: number) => `${(n / 1024).toFixed(1)} KB`;
const total = files.reduce((s, f) => s + statSync(f).size, 0);
console.log(`badecision built: ${files.length} files, ${kb(total)} (model ${kb(model.length)} from ${relative(ROOT, MODEL)}, kernel ${kernel.length} B, serious kernel ${smolKernel.length} B, head ${head.hidden} hidden)`);
